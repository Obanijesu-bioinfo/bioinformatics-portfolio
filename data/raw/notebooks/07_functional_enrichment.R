top_terms_md <- function(df, method) {
  if (nrow(df) == 0) return("_No significant terms._")
  if (method == "ORA") {
    out <- df |> arrange(p.adjust) |> head(10) |>
      transmute(Database = database, List = gene_list, Term = Description,
                `Genes` = paste0(Count, " (", GeneRatio, ")"),
                `Fold enr.` = sprintf("%.1f", fold_enrichment), `Adj. p` = fmt_p(p.adjust),
                `List genes` = gsub("/", ", ", geneID))
  } else {
    out <- df |> arrange(p.adjust) |> head(10) |>
      transmute(Database = database, Term = Description, `Set size` = setSize,
                NES = sprintf("%.2f", NES), `Adj. p` = fmt_p(p.adjust), Direction = direction)
  }
  md_table(out)
}
