run_ora <- function(db, genes, universe) {
  res <- switch(db,
    GO_BP = enrichGO(genes, OrgDb = org.Hs.eg.db, keyType = "ENTREZID", ont = "BP",
                     universe = universe, pAdjustMethod = "BH", pvalueCutoff = 1, qvalueCutoff = 1,
                     minGSSize = MIN_GS, maxGSSize = MAX_GS, readable = TRUE),
    GO_MF = enrichGO(genes, OrgDb = org.Hs.eg.db, keyType = "ENTREZID", ont = "MF",
                     universe = universe, pAdjustMethod = "BH", pvalueCutoff = 1, qvalueCutoff = 1,
                     minGSSize = MIN_GS, maxGSSize = MAX_GS, readable = TRUE),
    GO_CC = enrichGO(genes, OrgDb = org.Hs.eg.db, keyType = "ENTREZID", ont = "CC",
                     universe = universe, pAdjustMethod = "BH", pvalueCutoff = 1, qvalueCutoff = 1,
                     minGSSize = MIN_GS, maxGSSize = MAX_GS, readable = TRUE),
    KEGG = {
      k <- enrichKEGG(genes, organism = "hsa", keyType = "kegg", universe = universe,
                      pAdjustMethod = "BH", pvalueCutoff = 1, qvalueCutoff = 1,
                      minGSSize = MIN_GS, maxGSSize = MAX_GS, use_internal_data = FALSE)
      if (!is.null(k)) setReadable(k, OrgDb = org.Hs.eg.db, keyType = "ENTREZID") else k
    },
    Reactome = enrichPathway(genes, organism = "human", universe = universe,
                             pAdjustMethod = "BH", pvalueCutoff = 1, qvalueCutoff = 1,
                             minGSSize = MIN_GS, maxGSSize = MAX_GS, readable = TRUE))
  res
}
ratio_value <- function(x) vapply(strsplit(x, "/"), function(p) as.numeric(p[1]) / as.numeric(p[2]), 1)

ora_results <- list()
summary_rows <- list()
for (nm in names(ANALYSES)) {
  for (ln in c("all", "up", "down")) {
    genes_df <- inputs[[nm]]$lists[[ln]]
    mapped <- unique(na.omit(genes_df$entrez_id))
    for (db in DATABASES) {
      base_row <- data.frame(analysis = nm, role = ANALYSES[[nm]]$role, method = "ORA",
                             database = db, gene_list = ln, list_genes = nrow(genes_df),
                             list_genes_mapped = length(mapped),
                             universe_size = length(inputs[[nm]]$universe))
      if (length(mapped) < MIN_LIST_GENES) {
        summary_rows[[length(summary_rows) + 1]] <- cbind(base_row,
          list_genes_annotated_in_db = NA, terms_tested = NA, terms_significant = NA,
          status = sprintf("not run: %d mapped genes < minimum %d", length(mapped), MIN_LIST_GENES))
        next
      }
      res <- tryCatch(run_ora(db, mapped, inputs[[nm]]$universe),
                      error = function(e) structure(list(msg = conditionMessage(e)), class = "ora_error"))
      if (inherits(res, "ora_error")) {
        summary_rows[[length(summary_rows) + 1]] <- cbind(base_row,
          list_genes_annotated_in_db = NA, terms_tested = NA, terms_significant = NA,
          status = paste("ERROR:", res$msg))
        record_check(sprintf("ORA %s/%s/%s ran without database error", nm, ln, db), FALSE, res$msg)
        next
      }
      tab <- if (is.null(res)) data.frame() else as.data.frame(res)
      if (nrow(tab) > 0) {
        tab <- tab |>
          mutate(analysis = nm, role = ANALYSES[[nm]]$role, database = db, gene_list = ln,
                 fold_enrichment = ratio_value(GeneRatio) / ratio_value(BgRatio),
                 significant = p.adjust < ENRICH_ALPHA & Count >= MIN_OVERLAP) |>
          arrange(p.adjust)
        bh_ok <- isTRUE(all.equal(tab$p.adjust, p.adjust(tab$pvalue, method = "BH")))
        record_check(sprintf("ORA %s/%s/%s: BH recomputation matches", nm, ln, db), bh_ok)
        ora_results[[length(ora_results) + 1]] <- tab
      }
      annotated <- if (nrow(tab) > 0) length(unique(unlist(strsplit(tab$geneID, "/")))) else 0
      summary_rows[[length(summary_rows) + 1]] <- cbind(base_row,
        list_genes_annotated_in_db = annotated, terms_tested = nrow(tab),
        terms_significant = if (nrow(tab)) sum(tab$significant) else 0, status = "run")
      cat(sprintf("ORA %-14s %-4s %-8s: %4d terms tested, %3d significant\n", nm, ln, db,
                  nrow(tab), if (nrow(tab)) sum(tab$significant) else 0))
    }
  }
}
