# Reactome: reactome.db stores DBSCHEMAVERSION and SOURCEDATE (there is no
# REACTOMEVERSION field). SOURCEDATE is stored as a day count since 1970-01-01
# (e.g. 20459 = 2026-01-06); it is converted, and the raw value is kept.
reactome_version <- tryCatch({
  ri <- reactome.db::reactome_dbInfo()
  schema <- db_info_value(ri, "DBSCHEMAVERSION")
  src_raw <- db_info_value(ri, "SOURCEDATE")
  src_date <- if (!is.na(src_raw) && grepl("^[0-9]+$", src_raw)) {
    sprintf("%s (stored as %s)", format(as.Date(as.numeric(src_raw), origin = "1970-01-01")), src_raw)
  } else src_raw
  sprintf("reactome.db %s; schema version %s; source date %s; source %s",
          packageVersion("reactome.db"), schema, src_date, db_info_value(ri, "SOURCEURL"))
}, error = function(e) paste0("reactome.db ", packageVersion("reactome.db"),
                              "; metadata query failed: ", conditionMessage(e)))
# KEGG: the REST 'info' endpoint publishes an entry count and a "Last update" date,
# not a release number. Both are recorded as reported; no release number is invented.
kegg_release <- tryCatch({
  info <- paste(KEGGREST::keggInfo("pathway"), collapse = "\n")
  entries <- regmatches(info, regexpr("[0-9,]+ entries", info))
  updated <- regmatches(info, regexpr("Last update [0-9/]+", info))
  parts <- c(if (length(entries)) paste("KEGG pathway database:", entries),
             if (length(updated)) updated)
  if (length(parts)) paste(parts, collapse = "; ") else "KEGG info returned no entry count or update date"
}, error = function(e) paste("KEGG info query failed:", conditionMessage(e)))
