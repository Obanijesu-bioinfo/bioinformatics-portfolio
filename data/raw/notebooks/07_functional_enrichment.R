ora_plot <- function(nm, top_n = 6) {
  sig <- ora_all |> filter(analysis == nm, significant)
  runs <- enrichment_summary |> filter(analysis == nm, method == "ORA")
  if (nrow(sig) == 0) {
    lines <- runs |> group_by(gene_list) |>
      summarise(txt = sprintf("%s: %s", first(gene_list),
                              ifelse(all(status == "run"), sprintf("%d mapped genes; tested in 5 databases", first(list_genes_mapped)),
                                     first(status))), .groups = "drop")
    return(placeholder_plot(sprintf("ORA: %s", ANALYSES[[nm]]$label),
                            paste0("No GO, KEGG or Reactome term reached BH-adjusted p < 0.05\n",
                                   "(with >= 2 list genes).\n\n", paste(lines$txt, collapse = "\n"))))
  }
  top <- sig |> group_by(database, gene_list) |> slice_min(p.adjust, n = top_n, with_ties = FALSE) |>
    ungroup() |>
    mutate(term = wrap_term(Description), gene_list = factor(gene_list, levels = c("all", "up", "down")),
           database = factor(database, levels = DATABASES))
  top <- top |> group_by(database) |> mutate(term = reorder(term, fold_enrichment)) |> ungroup()
  ggplot(top, aes(fold_enrichment, term)) +
    geom_point(aes(size = Count, colour = -log10(p.adjust))) +
    scale_colour_gradient(low = "#9ec5f4", high = "#0d366b", name = expression(-log[10]~"adj. p")) +
    scale_size_continuous(range = c(2, 6), name = "Genes") +
    facet_grid(database ~ gene_list, scales = "free_y", space = "free_y") +
    labs(title = sprintf("ORA: %s", ANALYSES[[nm]]$label),
         subtitle = sprintf("Significant terms (BH-adjusted p < 0.05, >= 2 genes); top %d per database and gene list", top_n),
         x = "Fold enrichment (gene ratio / background ratio)", y = NULL,
         caption = "Universe: genes tested by DESeq2 (non-NA p-value) with a unique Entrez ID. Up/down lists tested only with >= 10 mapped genes.") +
    theme_portfolio() + theme(axis.text.y = element_text(size = 8, lineheight = 0.9))
}

