#!/usr/bin/env Rscript
# =============================================================================
# Phase 7: Functional enrichment analysis of GSE213410 DESeq2 results
# =============================================================================
# Analyses (never pooled):
#   C1            H9 hESC, 5-OXO-ETE vs Ethanol, A3 included   PRIMARY
#   C1_without_A3 same comparison, A3 excluded                 EXPLORATORY
#   C2            T21 hiPSC, Calcitriol vs DMSO                INDEPENDENT
#
# Inputs: Phase 6 tables (read only)
#   results/tables/C1_differential_expression.csv
#   results/tables/C1_differential_expression_without_A3.csv
#   results/tables/C2_differential_expression.csv
#
# Annotation layers (kept distinct):
#   Historical  Ensembl 97 (GRCh38.p12): transcript -> gene mapping (Phase 5)
#               and Ensembl gene -> NCBI Entrez gene mapping here
#               (EnsDb.Hsapiens.v97 from AnnotationHub).
#   Current     GO (org.Hs.eg.db / GO.db), Reactome (reactome.db),
#               KEGG (live KEGG REST query). Versions and query dates recorded.
#
# Gene ID rules:
#   - A gene is usable only if its Ensembl ID maps to exactly ONE Entrez ID
#     and that Entrez ID is linked to only ONE Ensembl ID among the 60,617
#     genes in the Phase 5 matrix. One-to-many and many-to-one mappings are
#     excluded and counted, never resolved by picking one.
#   - Genes without an Entrez ID (many lncRNAs, pseudogenes, TECs) are not
#     assigned to categories. They are reported, not forced in.
#
# ORA (over-representation; clusterProfiler, hypergeometric test):
#   - Gene lists: padj < 0.05 (all, up, down; direction = sign of MLE LFC).
#     A list is tested only if it has >= 10 usable (mapped) genes.
#   - Universe: genes with non-NA DESeq2 p-value (tested, incl. genes removed
#     only by independent filtering) and a usable Entrez ID.
#   - Term size 10-500 genes (within the universe), BH adjustment per
#     database/ontology, significant = BH-adjusted p < 0.05 and >= 2 list genes.
#
# GSEA (clusterProfiler/fgsea): ranking = DESeq2 Wald statistic for universe
#   genes with a finite statistic and usable Entrez ID; term size 10-500;
#   BH-adjusted p < 0.05; seed 42; eps = 0.
#
# No goseq (gene-length bias is discussed as a limitation).
#
# Outputs
#   Tables   results/tables/phase7_*.csv
#   Figures  results/figures/26-35_*.png
#   Summary  results/PHASE7_AUTOGENERATED_SUMMARY.md (machine-written overview)
#   The curated, reviewed report is results/PHASE7_REPORT.md. It is written by
#   hand from these outputs, and this script refuses to write to it.
#
# Post-run changes (2026-11-25; none alters any statistic, gene list or test):
#   - Auto-generated report moved from results/PHASE7_REPORT.md to
#     results/PHASE7_AUTOGENERATED_SUMMARY.md, with a guard against overwriting
#     the curated report.
#   - KEGG and Reactome provenance capture fixed (Step 3). The first run looked
#     for fields that do not exist ("Release ..." in KEGG, REACTOMEVERSION in
#     reactome.db) and recorded "release string not reported" and "(NA)".
#   - Running-score figures (28, 31, 34) now use the shared helper
#     07_gsea_running_score_plot.R: the top 3 sets of the database of the most
#     significant set, each curve labelled, title drawn by gseaplot2(). The
#     figures from the first run were redrawn from the saved tables by
#     07b_regenerate_running_score_figures.R, without rerunning enrichment.
#
# Run from the repository root:
#   Rscript data/raw/notebooks/07_functional_enrichment.R
# A full run takes about 1.5 h and re-queries live KEGG, so KEGG results can differ
# from the saved tables if KEGG has been updated since 2026-11-24.
# =============================================================================

