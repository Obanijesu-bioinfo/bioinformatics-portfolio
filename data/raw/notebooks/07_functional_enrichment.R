  record_check(sprintf("%s: table built from samples %s only", nm, paste(a$samples, collapse = ",")),
               identical(norm_samples, a$samples), paste(norm_samples, collapse = ","))
  record_check(sprintf("%s: gene IDs unique and well-formed Ensembl IDs", nm),
               !anyDuplicated(t$gene_id) && all(grepl("^ENSG\\d{11}$", t$gene_id)))
  recomputed_sig <- !is.na(t$padj) & t$padj < DE_ALPHA
  record_check(sprintf("%s: 'significant' equals padj < 0.05", nm),
               identical(as.logical(t$significant), recomputed_sig), sprintf("%d genes", sum(recomputed_sig)))
  dir_ok <- with(t[recomputed_sig, ], all((direction == "up") == (log2FoldChange_MLE > 0)))
  record_check(sprintf("%s: direction matches sign of MLE LFC", nm), dir_ok)
  in_universe <- !is.na(t$pvalue)
  record_check(sprintf("%s: significant genes are a subset of tested genes (non-NA p-value)", nm),
               all(in_universe[recomputed_sig]))
  record_check(sprintf("%s: Wald statistic finite for every tested gene", nm),
               all(is.finite(t$wald_stat[in_universe])),
               sprintf("%d tested; %d with NA padj kept in universe", sum(in_universe),
                       sum(in_universe & is.na(t$padj))))
}

