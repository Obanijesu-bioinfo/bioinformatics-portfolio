inputs <- list()
input_rows <- list()
for (nm in names(ANALYSES)) {
  t <- de_tables[[nm]] |>
    left_join(mapping |> select(gene_id, entrez_id, mapping_status), by = "gene_id")
  tested <- t |> filter(!is.na(pvalue))
  universe_entrez <- tested$entrez_id[!is.na(tested$entrez_id)]
  sig <- tested |> filter(!is.na(padj), padj < DE_ALPHA)
  lists <- list(all = sig, up = filter(sig, direction == "up"), down = filter(sig, direction == "down"))
  ranking <- tested |> filter(!is.na(entrez_id), is.finite(wald_stat)) |> arrange(desc(wald_stat))
  gene_list <- setNames(ranking$wald_stat, ranking$entrez_id)
  record_check(sprintf("%s: universe = tested genes with usable Entrez ID", nm),
               length(universe_entrez) == sum(!is.na(tested$entrez_id)) && !anyDuplicated(universe_entrez),
               sprintf("%d tested -> %d in universe", nrow(tested), length(universe_entrez)))
  record_check(sprintf("%s: every ORA gene list is a subset of its universe", nm),
               all(vapply(lists, function(l) all(na.omit(l$entrez_id) %in% universe_entrez), TRUE)))
  record_check(sprintf("%s: GSEA ranking finite, unique, sorted, equals universe", nm),
               all(is.finite(gene_list)) && !anyDuplicated(names(gene_list)) &&
                 !is.unsorted(rev(gene_list)) && setequal(names(gene_list), universe_entrez),
               sprintf("%d ranked genes; stat range %.2f to %.2f", length(gene_list),
                       min(gene_list), max(gene_list)))
  inputs[[nm]] <- list(lists = lists, universe = universe_entrez, gene_list = gene_list, tested = tested)
  for (ln in names(lists)) {
    l <- lists[[ln]]
    input_rows[[length(input_rows) + 1]] <- l |>
      transmute(analysis = nm, gene_list = ln, gene_id, gene_name, gene_biotype, direction,
                padj, log2FoldChange_MLE, shrinkage_collapsed, mapping_status, entrez_id,
                used_in_ORA = !is.na(entrez_id))
  }
  cat(sprintf("%s: tested %d | universe %d | ranked %d | lists all/up/down = %d/%d/%d genes (%d/%d/%d mapped)\n",
              nm, nrow(tested), length(universe_entrez), length(gene_list),
              nrow(lists$all), nrow(lists$up), nrow(lists$down),
              sum(!is.na(lists$all$entrez_id)), sum(!is.na(lists$up$entrez_id)),
              sum(!is.na(lists$down$entrez_id))))
}
