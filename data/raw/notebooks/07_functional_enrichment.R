run_gsea <- function(db, gene_list) {
  set.seed(SEED)
  res <- switch(db,
    GO_BP = gseGO(gene_list, ont = "BP", OrgDb = org.Hs.eg.db, keyType = "ENTREZID",
                  minGSSize = MIN_GS, maxGSSize = MAX_GS, eps = 0, pvalueCutoff = 1,
                  pAdjustMethod = "BH", seed = TRUE, by = "fgsea", verbose = FALSE),
    GO_MF = gseGO(gene_list, ont = "MF", OrgDb = org.Hs.eg.db, keyType = "ENTREZID",
                  minGSSize = MIN_GS, maxGSSize = MAX_GS, eps = 0, pvalueCutoff = 1,
                  pAdjustMethod = "BH", seed = TRUE, by = "fgsea", verbose = FALSE),
    GO_CC = gseGO(gene_list, ont = "CC", OrgDb = org.Hs.eg.db, keyType = "ENTREZID",
                  minGSSize = MIN_GS, maxGSSize = MAX_GS, eps = 0, pvalueCutoff = 1,
                  pAdjustMethod = "BH", seed = TRUE, by = "fgsea", verbose = FALSE),
    KEGG = gseKEGG(gene_list, organism = "hsa", keyType = "kegg", minGSSize = MIN_GS,
                   maxGSSize = MAX_GS, eps = 0, pvalueCutoff = 1, pAdjustMethod = "BH",
                   seed = TRUE, by = "fgsea", verbose = FALSE, use_internal_data = FALSE),
    Reactome = gsePathway(gene_list, organism = "human", minGSSize = MIN_GS, maxGSSize = MAX_GS,
                          eps = 0, pvalueCutoff = 1, pAdjustMethod = "BH", seed = TRUE,
                          by = "fgsea", verbose = FALSE))
  res
}
gsea_objects <- list()
gsea_results <- list()
for (nm in names(ANALYSES)) {
  for (db in DATABASES) {
    res <- tryCatch(run_gsea(db, inputs[[nm]]$gene_list),
                    error = function(e) structure(list(msg = conditionMessage(e)), class = "gsea_error"))
    base_row <- data.frame(analysis = nm, role = ANALYSES[[nm]]$role, method = "GSEA",
                           database = db, gene_list = "ranked (Wald statistic)",
                           list_genes = length(inputs[[nm]]$gene_list),
                           list_genes_mapped = length(inputs[[nm]]$gene_list),
                           universe_size = length(inputs[[nm]]$universe))
    if (inherits(res, "gsea_error")) {
      record_check(sprintf("GSEA %s/%s ran without database error", nm, db), FALSE, res$msg)
      summary_rows[[length(summary_rows) + 1]] <- cbind(base_row, list_genes_annotated_in_db = NA,
        terms_tested = NA, terms_significant = NA, status = paste("ERROR:", res$msg))
      next
    }
    # Convert leading-edge Entrez IDs to gene symbols for readability
    res <- tryCatch(setReadable(res, OrgDb = org.Hs.eg.db, keyType = "ENTREZID"),
                    error = function(e) res)
    gsea_objects[[paste(nm, db, sep = "|")]] <- res
    tab <- as.data.frame(res)
    if (nrow(tab) > 0) {
      tab <- tab |>
        mutate(analysis = nm, role = ANALYSES[[nm]]$role, database = db,
               direction = ifelse(NES > 0, "higher in treatment", "lower in treatment"),
               significant = p.adjust < ENRICH_ALPHA) |>
        arrange(p.adjust)
      bh_ok <- isTRUE(all.equal(tab$p.adjust, p.adjust(tab$pvalue, method = "BH")))
      record_check(sprintf("GSEA %s/%s: BH recomputation matches", nm, db), bh_ok)
      gsea_results[[length(gsea_results) + 1]] <- tab
    }
    summary_rows[[length(summary_rows) + 1]] <- cbind(base_row, list_genes_annotated_in_db = NA,
      terms_tested = nrow(tab), terms_significant = if (nrow(tab)) sum(tab$significant) else 0,
      status = "run")
    cat(sprintf("GSEA %-14s %-8s: %4d terms tested, %3d significant (up %d / down %d)\n", nm, db,
                nrow(tab), if (nrow(tab)) sum(tab$significant) else 0,
                if (nrow(tab)) sum(tab$significant & tab$NES > 0) else 0,
                if (nrow(tab)) sum(tab$significant & tab$NES < 0) else 0))
  }
}
